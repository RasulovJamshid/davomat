interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, variables?: Record<string, string | number>) => string;
}
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem("atlas.locale");
    return saved === "uz" || saved === "ru" ? saved : "en";
  });
  const setLocale = (next: Locale) => {
    localStorage.setItem("atlas.locale", next);
    setLocaleState(next);
  };
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const value = useMemo<I18nValue>(
    () => ({
      locale,
      setLocale,
      t: (key, variables) => {
        let result = dictionaries[locale][key] ?? en[key] ?? key;
        for (const [name, value] of Object.entries(variables ?? {}))
          result = result.replaceAll(`{${name}}`, String(value));
        return result;
      },
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export const intlLocale = (locale: Locale) =>
  locale === "uz" ? "uz-UZ" : locale === "ru" ? "ru-RU" : "en-US";

export function LanguageSwitcher({ compact = false }: { compact?: boolean }) {
  const { locale, setLocale, t } = useI18n();
  return (
    <label className={`language-switcher ${compact ? "compact" : ""}`}>
      <span>{t("language")}</span>
      <select
        value={locale}
        onChange={(event) => setLocale(event.target.value as Locale)}
        aria-label={t("language")}
      >
        <option value="en">EN</option>
        <option value="uz">UZ</option>
        <option value="ru">RU</option>
      </select>
    </label>
  );
}

